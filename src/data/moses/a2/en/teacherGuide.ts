const makeSection = (p: ChapterPlan): TeacherGuideSection => ({
  chapter: p.chapter,
  timing: p.timing,
  objectives: [
    `Understand and retell the chapter’s main event: ${p.focus}.`,
    `Find one clear detail from the current student text, especially ${p.evidence}.`,
    `Use A2 language support from the chapter text: ${p.languageSupport}.`,
    `Show the value through a simple action: ${p.valueAction}.`,
  ],
  pedagogy: `Use a TYMM-compatible meaning-first cycle: visual/audio prediction → listening/reading for gist → short evidence check → guided noticing of language already present in the chapter → pair speaking or short writing → reflection. Keep A2 output short and scaffolded. Values should appear through an observable action, not as a detached moral lecture: ${p.valueAction}.`,
  priorKnowledge: ['Recall one event from the previous chapter.', 'Use the picture, title and a few current Word Notes to predict meaning.'],
  anticipatedMisconceptions: [p.misconception],
  grammarFocus: `Teacher-side language support derived from the current chapter text: ${p.languageSupport}. There is currently no separate student-facing Language Focus section in Moses A2; do not tell learners to open one until that source section exists.`,
  pronunciationFocus: 'Use only words and names that occur on the current page. Model one short sentence from the story, then let learners repeat it with clear word stress, pauses and intelligible A2 pronunciation.',
  beforeReading: [`Use the title and image to ask one simple prediction related to: ${p.focus}.`, 'Preview only 3–5 Word Notes needed to understand the chapter.'],
  duringReading: [`Listen/read first for the main event, then locate this evidence: ${p.evidence}.`, 'Pause once or twice for short who/what/where/why questions; do not overload the first reading with grammar explanation.'],
  afterReading: [
    `Discuss in simple language: ${p.discussion}`,
    'Complete the exercise/Quick Challenge that actually appears on the current chapter page and correct the answer from the text.',
    `Guide a 4–6 minute noticing task using an exact sentence from the chapter for: ${p.languageSupport}.`,
    'Finish with 2–4 spoken sentences or 3–5 written A2 sentences in a new everyday context using one target pattern.',
  ],
  lessonPlan: '0–5 min: picture/title prediction. 5–10: essential vocabulary. 10–20: listen/read for gist. 20–27: reread and locate evidence. 27–32: current page exercise and correction. 32–37: teacher-side language noticing from the story text. 37–42: pair speaking or short writing. Final 2–3 min: value/action exit ticket.',
  discussionPoints: [p.discussion, `Which sentence or detail supports your answer: ${p.evidence}?`, 'What can we say from the text without adding information that is not there?'],
  interactiveTips: ['Use the chapter audio if it is available on the current page.', 'Use only the hotspots and Word Notes that actually exist on that chapter page.', 'Use the page exercise after meaning is established.', 'Do not refer learners to worksheets, maps, cards or a separate Language Focus unless the resource is actually present or the teacher explicitly creates it.'],
  differentiation: {
    strugglingLearners: 'Give two answer choices, sentence starters and permission to point to the evidence before speaking. Keep production to 1–2 correct sentences if necessary.',
    fastFinishers: `Write 5–7 connected A2 sentences answering: ${p.discussion} Include one detail from the story and one use of the chapter language support.`,
  },
  formativeAssessment: ['Main-event comprehension', 'Correct location of one textual detail', 'Intelligible use of one chapter language pattern', 'Current page exercise correction', 'Simple value-to-action transfer'],
  expectedResponses: [`Learners should refer to ${p.evidence}.`, `A suitable A2 response uses short connected sentences and does not strengthen the story beyond what it states.`, `The language target is: ${p.languageSupport}.`],
  transferTask: `Use one pattern from “${p.languageSupport}” in a new A2 situation, then give one practical example of ${p.valueAction}.`,
  teacherReflection: 'Did learners understand the story before language analysis? Did I use only resources that exist on the page? Was the language support taken from the chapter itself? Could learners produce a short meaningful A2 response?',
});

