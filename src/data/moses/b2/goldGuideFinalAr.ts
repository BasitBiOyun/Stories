import type {
  PageData,
  StudentGuideMetadata,
  StudentGuideSection,
  TeacherGuideMetadata,
  TeacherGuideSection,
} from '../../../types';
import { mosesB2PagesAr } from './ar/pages';
import { mosesB2QuestionSpecsAr } from './goldLearningAr';

const storyPages = mosesB2PagesAr.filter((page) => page.type === 'story');
const specByChapter = new Map(mosesB2QuestionSpecsAr.map((spec) => [spec.chapterId, spec]));

const chapterLabel = (page: PageData): string => `الفصل ${page.id}: ${page.title}`;
const vocabularyWords = (page: PageData): string[] => (page.vocabulary ?? []).slice(0, 5).map((entry) => entry.word);

const teacherSection = (page: PageData): TeacherGuideSection => {
  const spec = specByChapter.get(page.id);
  if (!spec) throw new Error(`Moses B2 Arabic Gold: guide evidence spec for chapter ${page.id} is missing.`);
  const words = vocabularyWords(page);
  const vocabularyText = words.length ? words.join('، ') : 'مفردات الفصل';

  return {
    chapter: chapterLabel(page),
    timing: '55 دقيقة',
    objectives: [
      `الإجابة عن سؤال التحليل المركزي للفصل وتبريرها: ${spec.question}`,
      'الاستناد إلى دليلين على الأقل من نص الفصل المعتمد عند تفسير الفكرة أو العلاقة.',
      `استخدام مفردات مختارة من الفصل في سياقها: ${vocabularyText}.`,
      'كتابة تفسير قصير منظم يميز بين ما يذكره النص وما يعد تأملاً مفتوحاً.',
    ],
    pedagogy: `اعتمد القراءة القريبة القائمة على الدليل حول محور «${spec.title}». لا تضف معلومة تاريخية أو دينية من خارج الفصل، واطلب من المتعلم تحديد العبارة أو الحدث الذي يدعم تفسيره قبل الانتقال إلى التأمل.`,
    grammarFocus: 'لغة التعليل والمقارنة والاستدلال: لأن، لذلك، نتيجةً لذلك، بينما، في المقابل، وفقاً للفصل، يدل هذا على، ويؤيد ذلك.',
    pronunciationFocus: words.length
      ? `راجع النطق الواضح والبنية الصوتية لهذه الكلمات والعبارات: ${vocabularyText}.`
      : 'راجع نطق مفردات الفصل الأساسية في سياق الجملة.',
    lessonPlan: `0–7 د: معاينة العنوان والصورة ونقاط التفاعل ومفردات الفصل. 7–20 د: قراءة أولى للفكرة العامة. 20–33 د: قراءة ثانية وتحديد دليلين يرتبطان بمحور «${spec.title}». 33–42 د: مقارنة خيارات سؤال التحدي وبيان سبب ضعف الخيارين الآخرين. 42–48 د: تنفيذ Quick Challenge؛ عند الخطأ يعود الطالب إلى الفقرة ذات الصلة ثم يحاول ثانية. 48–55 د: كتابة إجابة قصيرة وفق نموذج: ادعاء → دليل → تفسير، ثم بطاقة خروج.`,
    discussionPoints: [
      spec.question,
      'ما الدليلان الأقوى في هذا الفصل لدعم إجابتك؟ ولماذا؟',
      'أي تفسير بديل هو الأضعف دعماً من النص؟ وما الدليل الذي يستبعده؟',
    ],
    differentiation: {
      fastFinishers: `اكتب فقرة تحليلية من 120–150 كلمة حول «${spec.title}» مستخدماً دليلين من الفصل وعبارتي ربط على الأقل.`,
      strugglingLearners: 'استخدم جدولاً من ثلاثة أعمدة: الفكرة → الدليل من الفصل → ما الذي يوضحه الدليل. أكمل صفاً واحداً قبل إعادة المحاولة.',
    },
    interactiveTips: [
      'استخدم نقاط التفاعل كإشارات للبحث عن الدليل، لا بديلاً عن قراءة الفقرة الأصلية.',
      'اطلب من المتعلمين استنتاج معنى الكلمة من السياق قبل فتح Word Notes.',
      'اجعل Quick Challenge أداة تعزيز: بعد الإجابة الضعيفة أو الخاطئة يعود المتعلم إلى النص ثم يعيد المحاولة.',
    ],
    assessmentTools: {
      rubric: ['اختيار الدليل', 'الاستنتاج والتحليل B2', 'المفردات في السياق', 'وضوح التفسير'],
      exitTicket: ['اكتب فكرة واحدة يدعمها الفصل', 'اكتب العبارة أو الحدث الذي يدعمها'],
    },
    extraResources: undefined,
  };
};

