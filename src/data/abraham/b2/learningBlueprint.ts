const V = (chapterId: number, index = 0): LocalizedText => {
  const target = abrahamB2HighlightTargets[chapterId]?.[index];
  if (!target) throw new Error(`Abraham B2 Blueprint: missing canonical Word Note ${index + 1} for Chapter ${chapterId}.`);
  return L(target.en.word, target.ar.word);
};

