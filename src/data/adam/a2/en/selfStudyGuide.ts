export const adamA2StudentGuideText = `
# A2 SELF-STUDY GUIDE
## The Story of Prophet Adam

### What is this guide for?

This guide helps Grades 5–6 learners study the story at A2.

Your goal is simple:

- understand the story,
- learn useful words,
- listen and read,
- try the activities,
- read again when you need help.

You do not need to understand every word the first time.

### Use every chapter like this

1. **Look** at the title and image.
2. **Listen** once and follow the text.
3. **Read** one short part at a time.
4. Check the underlined words in **Word Notes**.
5. Do the **Quick Challenge**.
6. If you are wrong, find the answer sentence.
7. Read it again.
8. Try again.
9. Say one fact and one new word.

### Word Notes

When you see an underlined word:

- read the full sentence,
- try to guess the meaning,
- check Word Notes,
- read the sentence again.

You do not need to translate every word.

### Quick Challenge

The Quick Challenge helps you learn. It is not a big test.

Try the activity after you read the chapter. If you are not sure, go back to the story. If your answer is wrong, find the answer sentence and read it again.

Use this simple plan:

**Read → Try → Check → Read again → Try again**

### After every chapter

Do three small things:

- Say one important fact.
- Say one new word and its meaning.
- Write one short sentence.

This can take only two or three minutes.

### Knowledge Check and Review Challenge

After the story chapters, do the Knowledge Check.

The Review Challenge has **8 questions**.

If you do not remember an answer:

1. Find the chapter.
2. Find the answer sentence.
3. Read it again.
4. Try the question again.

### Final Challenge

The Final Challenge has **10 questions** about the whole story.

Before you start:

- look at the ten chapter titles,
- remember one fact from each chapter,
- review hard Word Notes.

Then start the challenge.

### Listening

If a chapter is hard:

- listen once,
- listen again and follow the text,
- play only the hard part again,
- read that part by yourself.

### New words

Choose three to five useful words from each chapter.

In a notebook, write:

**word | meaning | one sentence**

Read old words again before you add many new words.

### If the story feels hard

Make the task smaller:

- read one short part,
- check the underlined words,
- listen to that part,
- answer one question,
- then continue.

### At the end of the book

Look at Chapters 1–10. Say one fact from each chapter. Then check the story and fix any fact you forgot.

You are ready for the Review Challenge and Final Challenge when you can remember the main ideas of the story.
`;
