// The Master Glossary lists every Word Note with its chapter and the story sentence it comes from.
const storySentences = (content: string): string[] => content
  .split(/\n+/)
  .flatMap(paragraph => paragraph.trim().split(/(?<=[.!؟?]["»”]?)\s+/))
  .map(sentence => sentence.trim())
  .filter(Boolean);
const masterGlossary: NonNullable<PageData['vocabulary']> = yunusEmreB1RawPagesAr
  .filter(page => page.type === 'story')
  .flatMap(page => (page.vocabulary ?? []).map(item => ({
    ...item,
    chapter: page.id,
    chapterTitle: page.title,
    storyExample: storySentences(page.content ?? '').find(sentence => highlightPhraseOccurs(sentence, item.word, 'ar')),
  })));

export const yunusEmreB1PagesAr: PageData[] = yunusEmreB1RawPagesAr.map(page => (
  page.type === 'glossary' ? { ...page, vocabulary: masterGlossary } : page
));
